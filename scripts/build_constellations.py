    assert len(ROWS) == 88, f"expected 88 constellations, got {len(ROWS)}"
    codes = [row[0] for row in ROWS]
    assert len(set(codes)) == 88, "duplicate constellation codes"
    entries = []
    for code, ra, dec, major, minor, stars, note_zh, note_en in ROWS:
        assert 0.0 <= ra < 24.0, code
        assert -90.0 <= dec <= 90.0, code
        assert major >= minor > 0, code
        assert 2 <= len(stars) <= 4, code
        entries.append({
            "code": code,
            "centerRaHours": ra,
            "centerDecDeg": dec,
            "sizeMajorDeg": major,
            "sizeMinorDeg": minor,
            "brightStars": [
                {"nameZh": zh, "nameEn": en, "magnitude": mag} for zh, en, mag in stars
            ],
            "noteZh": note_zh,
            "noteEn": note_en,
        })
    doc = {
        "schemaVersion": 1,
        "dataVersion": DATA_VERSION,
        "source": SOURCE,
        "constellations": entries,
    }
    OUT.write_text(
        json.dumps(doc, ensure_ascii=False, indent=1, sort_keys=False) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({len(entries)} constellations)")


